function translateDynamic(text: string): string {
  const exact = zh[text]
  if (exact) return exact
  if (text === 'CSV must be UTF-8 encoded') return 'CSV 必须使用 UTF-8 编码。'
  if (text === 'CSV must contain a header row') return 'CSV 必须包含表头行。'
  if (text === 'CSV column names must be unique') return 'CSV 列名必须唯一。'
  if (text === 'CSV must contain at least one data row') return 'CSV 至少需要一行数据。'
  if (text === 'Naive timestamps require an explicit IANA timezone before import') return '无时区时间戳必须在导入前明确指定 IANA 时区。'
  const discoveryFactorEvidence = text.match(/^(\d+)D Factor evidence known when this hypothesis revision was created, from the saved (RESEARCH|VALIDATION|HOLDOUT) evaluation; no metric is recomputed in Discovery\.$/)
  if (discoveryFactorEvidence) return `${discoveryFactorEvidence[1]} 日因子证据，来自创建该研究假设修订版时已经保存的${translateDynamic(discoveryFactorEvidence[2])}评估；策略发现不会重新计算这些指标。`
  const discoveryStageLabel = text.match(/^(.+) · (RESEARCH|VALIDATION|HOLDOUT)$/)
  if (discoveryStageLabel) return `${translateDynamic(discoveryStageLabel[1])} · ${translateDynamic(discoveryStageLabel[2])}`
  const discoveryRedundancyLabel = text.match(/^(HIGH REDUNDANCY|RELATED|LOW REDUNDANCY) · Factor pair$/)
  if (discoveryRedundancyLabel) return `${translateDynamic(discoveryRedundancyLabel[1].replaceAll(' ', '_'))} · 因子对`
  const discoveryWalkForwardLabel = text.match(/^Walk-Forward Stability · (.+)$/)
  if (discoveryWalkForwardLabel) return `滚动前向稳定性 · ${translateDynamic(discoveryWalkForwardLabel[1])}`
  const discoveryPortfolioLabel = text.match(/^Candidate Portfolio · (RESEARCH|VALIDATION|HOLDOUT)$/)
  if (discoveryPortfolioLabel) return `候选组合 · ${translateDynamic(discoveryPortfolioLabel[1])}`
  const warmup = text.match(/^Need two complete (\d+)-bar windows$/)
  if (warmup) return `需要两个完整的 ${warmup[1]} 根 K 线窗口`
  const lastRun = text.match(/^Last run · (.+)$/)
  if (lastRun) return `上次运行 · ${lastRun[1]}`
  const loading = text.match(/^Loading (.+)\.$/)
  if (loading) return `正在加载 ${loading[1]}。`
  const warningsElsewhere = text.match(/^No look-ahead warnings were attached to this event\. (\d+) recorded elsewhere in this trace\.$/)
  if (warningsElsewhere) return `本事件没有关联前视偏差警告；此追踪的其他位置记录了 ${warningsElsewhere[1]} 条。`
  const minimum = text.match(/^(.+) must be at least (.+)\.$/)
  if (minimum) return `${translateDynamic(minimum[1])}必须至少为 ${minimum[2]}。`
  const shortEntry = text.match(/^z-score (.+) > entry threshold (.+)$/)
  if (shortEntry) return `Z 分数 ${shortEntry[1]} > 入场阈值 ${shortEntry[2]}`
  const longEntry = text.match(/^z-score (.+) < -entry threshold (.+)$/)
  if (longEntry) return `Z 分数 ${longEntry[1]} < 负入场阈值 ${longEntry[2]}`
  const exit = text.match(/^\|z-score\| (.+) < exit threshold (.+)$/)
  if (exit) return `|Z 分数| ${exit[1]} < 离场阈值 ${exit[2]}`
  const splitEvidence = text.match(/^Train (.+); test (.+)\.$/)
  if (splitEvidence) return `训练集 ${splitEvidence[1]}；测试集 ${splitEvidence[2]}。`
  const frictionEvidence = text.match(/^(\d+ bps) return (.+); (\d+ bps) return (.+)\.$/)
  if (frictionEvidence) return `${frictionEvidence[1]} 收益 ${frictionEvidence[2]}；${frictionEvidence[3]} 收益 ${frictionEvidence[4]}。`
  const delayEvidence = text.match(/^(t\+\d+) return (.+); (t\+\d+) return (.+); (t\+\d+) unfilled signals (\d+)\.$/)
  if (delayEvidence) return `${delayEvidence[1]} 收益 ${delayEvidence[2]}；${delayEvidence[3]} 收益 ${delayEvidence[4]}；${delayEvidence[5]} 未成交信号 ${delayEvidence[6]} 个。`
  const reordered = text.match(/^ROWS_REORDERED: (\d+) row positions changed$/)
  if (reordered) return `行顺序已调整：${reordered[1]} 个位置发生变化。`
  const gaps = text.match(/^DATA_ALIGNMENT_GAP: (\d+) symbol\/timestamp cells are missing; strict synchronized runs use only the intersection$/)
  if (gaps) return `数据对齐缺口：缺少 ${gaps[1]} 个标的/时间戳单元；严格同步运行只使用各标的时间戳交集。`
  const duplicateBars = text.match(/^Duplicate \(symbol, timestamp\) bars detected: (\d+); import rejected$/)
  if (duplicateBars) return `检测到 ${duplicateBars[1]} 条重复的（标的，时间戳）K 线；已拒绝导入。`
  const missingClose = text.match(/^close is missing in (\d+) row\(s\); imports never forward-fill prices$/)
  if (missingClose) return `有 ${missingClose[1]} 行缺少收盘价；导入不会自动向前填充价格。`
  const missingSymbolLine = text.match(/^Missing symbol at CSV line (\d+)$/)
  if (missingSymbolLine) return `CSV 第 ${missingSymbolLine[1]} 行缺少标的。`
  const invalidValueLine = text.match(/^Invalid (open|high|low|close|volume) value at CSV line (\d+)$/)
  if (invalidValueLine) return `CSV 第 ${invalidValueLine[2]} 行的${translateDynamic(invalidValueLine[1])}无效。`
  const positiveClose = text.match(/^close must be positive at CSV line (\d+)$/)
  if (positiveClose) return `CSV 第 ${positiveClose[1]} 行的收盘价必须大于 0。`
  const unknownTimezone = text.match(/^Unknown timezone '(.+)'$/)
  if (unknownTimezone) return `未知时区“${unknownTimezone[1]}”。`
  const mappingMissing = text.match(/^Column mapping is missing required fields: (.+)$/)
  if (mappingMissing) return `列映射缺少必需字段：${mappingMissing[1]}。`
  const mappedMissing = text.match(/^Mapped source columns do not exist: (.+)$/)
  if (mappedMissing) return `映射的源列不存在：${mappedMissing[1]}。`
  const unsupportedFields = text.match(/^Unsupported canonical fields: (.+)$/)
  if (unsupportedFields) return `不支持的标准字段：${unsupportedFields[1]}。`
  const missingRequiredFields = text.match(/^Missing required fields: (.+)$/)
  if (missingRequiredFields) return `缺少必需字段：${missingRequiredFields[1]}。`
  const missingRequiredSymbols = text.match(/^Missing required symbols: (.+)$/)
  if (missingRequiredSymbols) return `缺少必需标的：${missingRequiredSymbols[1]}。`
  const symbolCount = text.match(/^Strategy requires (\d+) symbols(?: exactly)?; dataset provides (\d+)$/)
  if (symbolCount) return `策略需要 ${symbolCount[1]} 个标的；当前数据集提供 ${symbolCount[2]} 个。`
  const historyCount = text.match(/^Strategy requires at least (\d+) synchronized bars; dataset provides (\d+)$/)
  if (historyCount) return `策略至少需要 ${historyCount[1]} 根同步 K 线；当前数据集提供 ${historyCount[2]} 根。`
  const missingDataset = text.match(/^Dataset '(.+)' was not found$/)
  if (missingDataset) return `未找到数据集“${missingDataset[1]}”。`
  const missingStrategy = text.match(/^Strategy '(.+)' is not currently registered\.$/)
  if (missingStrategy) return `策略“${missingStrategy[1]}”当前未注册。`
  const firstBehavior = text.match(/^First (feature|condition|signal|position|order|execution) behavior differs at (.+)$/)
  if (firstBehavior) return `首次${translateDynamic(firstBehavior[1].toUpperCase())}行为分歧发生在 ${firstBehavior[2]}。`
  if (text === 'The two traces have no behavioral divergence.') return '两条追踪没有行为分歧。'
  if (text === 'Exit Z must be smaller than Entry Z.') return '离场 Z 值必须小于入场 Z 值。'
  return text
}

interface I18nValue {
  language: Language
  setLanguage: (language: Language) => void
  tr: (text: string) => string
}

const I18nContext = createContext<I18nValue>({ language: 'en', setLanguage: () => undefined, tr: (text) => text })

function initialLanguage(): Language {
  try { return window.localStorage.getItem('vqd-language') === 'en' ? 'en' : 'zh' }
  catch { return 'zh' }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(initialLanguage)
  useEffect(() => { document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en' }, [language])
  const value = useMemo<I18nValue>(() => ({
    language,
    setLanguage(next) {
      setLanguageState(next)
      try { window.localStorage.setItem('vqd-language', next) } catch { /* Storage may be unavailable. */ }
    },
    tr: language === 'zh' ? translateDynamic : (text) => text,
  }), [language])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() { return useContext(I18nContext) }
